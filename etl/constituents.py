# Lookup dictionary mappings
CONSTITUENTS_BY_TICKER = {item["ticker_symbol"]: item for item in NIFTY_50_CONSTITUENTS}
CONSTITUENTS_BY_YFINANCE = {item["yfinance_symbol"]: item for item in NIFTY_50_CONSTITUENTS}


def get_all_tickers() -> List[str]:
    """Returns a list of all 50 constituent ticker symbols."""
    return [c["ticker_symbol"] for c in NIFTY_50_CONSTITUENTS]


def get_all_yfinance_symbols() -> List[str]:
    """Returns a list of all 50 Yahoo Finance symbol strings (e.g. TICKER.NS)."""
    return [c["yfinance_symbol"] for c in NIFTY_50_CONSTITUENTS]


def get_constituent(ticker: str) -> Dict[str, Any]:
    """Looks up constituent metadata by ticker or yfinance symbol."""
    clean_ticker = ticker.upper().replace(".NS", "")
    if clean_ticker in CONSTITUENTS_BY_TICKER:
        return CONSTITUENTS_BY_TICKER[clean_ticker]
    if ticker in CONSTITUENTS_BY_YFINANCE:
        return CONSTITUENTS_BY_YFINANCE[ticker]
    raise KeyError(f"Ticker '{ticker}' not found in Nifty 50 constituents list.")
